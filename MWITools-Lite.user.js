	function handleBattleUpdated(obj) {
		if (!settingsMap.showDamage.isTrue || !monstersHP.length) return;
		const { mMap, pMap } = obj;
		const playerIndices = Object.keys(pMap);
		let castPlayer = null;
		for (const playerIndex of playerIndices) {
			if (pMap[playerIndex].cMP < playersMP[playerIndex]) castPlayer = playerIndex;
			playersMP[playerIndex] = pMap[playerIndex].cMP;
		}
		monstersHP.forEach((previousHP, monsterIndex) => {
			const monster = mMap[monsterIndex];
			if (!monster) return;
			const damage = previousHP - monster.cHP;
			monstersHP[monsterIndex] = monster.cHP;
			if (damage <= 0) return;
			if (playerIndices.length > 1) {
				if (castPlayer !== null) addPlayerDamage(castPlayer, damage);
			} else addPlayerDamage(playerIndices[0], damage);
		});
		for (const playerIndex of playerIndices) players[playerIndex].currentAction = pMap[playerIndex].abilityHrid ? pMap[playerIndex].abilityHrid : pMap[playerIndex].isAutoAtk ? "auto" : "idle";
		endTime = Date.now();
		updateStatisticsPanel();
	}
