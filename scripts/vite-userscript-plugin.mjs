import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const USERSCRIPT_ENTRY_ID = "virtual:mwitools-userscript";
const RESOLVED_ENTRY_ID = `\0${USERSCRIPT_ENTRY_ID}.ts`;

const normalizeNewlines = (content) => content.replace(/\r\n?/g, "\n");

export function userscriptBundlePlugin({ sourceDirectory, outputFileName, installableOutputPath }) {
    const resolveSource = (relativePath) => path.join(sourceDirectory, relativePath);
    const readSource = async (relativePath) => normalizeNewlines(await readFile(resolveSource(relativePath), "utf8")).trimEnd();

    return {
        name: "mwitools-userscript-bundle",
        apply: "build",
        enforce: "pre",

        resolveId(id) {
            return id === USERSCRIPT_ENTRY_ID ? RESOLVED_ENTRY_ID : null;
        },

        async buildStart() {
            for (const file of ["manifest.json", "userscript.meta.txt", "preamble.txt"]) {
                this.addWatchFile(resolveSource(file));
            }
        },

        async load(id) {
            if (id !== RESOLVED_ENTRY_ID) {
                return null;
            }

            this.addWatchFile(resolveSource("manifest.json"));
            const manifest = JSON.parse(await readSource("manifest.json"));
            const moduleBlocks = [];
            for (const module of manifest.modules) {
                const modulePath = resolveSource(module.path);
                this.addWatchFile(modulePath);
                const source = normalizeNewlines(await readFile(modulePath, "utf8")).trimEnd();
                moduleBlocks.push(`// #region ${module.name}\n${source}\n// #endregion ${module.name}`);
            }

            return `"use strict";\n\n${moduleBlocks.join("\n\n")}\n`;
        },

        async generateBundle(_outputOptions, bundle) {
            const metadata = await readSource("userscript.meta.txt");
            const preamble = await readSource("preamble.txt");
            const generatedNotice = [
                "/*",
                " * This file is generated by Vite. Edit TypeScript files in src/ and run npm run build.",
                " */",
            ].join("\n");
            const banner = `${metadata}\n\n${generatedNotice}\n\n${preamble}\n\n`;

            const entryChunk = bundle[outputFileName];
            if (!entryChunk || entryChunk.type !== "chunk") {
                this.error(`Unable to find generated userscript chunk: ${outputFileName}`);
            }
            entryChunk.code = `${banner}${entryChunk.code}`;
        },

        async writeBundle(_outputOptions, bundle) {
            const entryChunk = bundle[outputFileName];
            if (!entryChunk || entryChunk.type !== "chunk") {
                this.error(`Unable to write generated userscript chunk: ${outputFileName}`);
            }
            await writeFile(installableOutputPath, entryChunk.code, "utf8");
        },
    };
}
